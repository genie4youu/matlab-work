function emit_interp(p, keep, num)
%EMIT_INTERP  해석 절을 쓴다. 기존 해석이 있으면 그것을 되돌려 놓는다.
%
%   emit_interp(p, keep, num)
%     p    : fprintf 래퍼 (@(varargin) fprintf(fid, varargin{:}))
%     keep : read_interp 이 회수한 기존 해석 본문. 비었으면 뼈대를 쓴다
%     num  : 절 번호 (SubSystem 은 5, ModelReference 는 4, Chart 는 8)
%
%   🔴 이 함수가 해석 절 구조(규칙 R17)의 **단일 정의**다.
%   ──────────────────────────────────────────────────────────
%   gen_vault_tree.m · gen_vault_charts.m 이 이 함수를 공유하고,
%   audit_coverage.m 의 판정 ④ 가 같은 소절 제목을 검사한다.
%   구조를 스크립트마다 옮겨 적으면 언젠가 갈라지고, 갈라지면
%   감사가 영원히 실패하거나 영원히 통과한다 (vault_segs.m 와 같은 이유).
%
%   왜 뼈대를 미리 박아두나
%   ──────────────────────
%   2026-08-05. 해석이 사실은 맞는데 읽는 사람이 이해하지 못하는 상태가 됐다.
%   원인은 「무엇을 쓸 것인가」가 자유서술이어서, 쓰는 쪽이 이미 아는 것을
%   생략해도 아무도 잡지 못한 것이다. 소절을 미리 박아두면 빈칸이 눈에 보인다.
%
%   ⚠️ 뼈대에는 자리표시자 문구를 남긴다. 그래야 read_interp 가 「아직 안 썼다」로
%      인식하고, audit_coverage 판정 ② 도 계속 실패로 잡는다.

    p('## %d. 해석\n\n', num);
    if ~isempty(keep)
        p('%s\n\n', keep);
        return
    end

    p('> 아직 채우지 않았다. 기계 추출만 있는 상태다. 아래 소절을 규칙 R17 대로 채운다.\n\n');
    p('### %d.1 한 줄로\n\n', num);
    p('<!-- 전문용어 없이 두 문장. 「이 블록은 무엇을 하는 곳인가」 -->\n\n');
    p('### %d.2 한 스텝에서 일어나는 일\n\n', num);
    p('<!-- 정렬 순서대로 번호를 매겨 따라간다. 최소 2단계. 블록 이름을 실제로 쓴다 -->\n\n');
    p('### %d.3 숫자의 근거\n\n', num);
    p('<!-- | 수치 | 어디서 나왔나 | 무엇을 뜻하는가 |  숫자가 없으면 「해당 없음」이라고 쓴다 -->\n\n');
    p('### %d.4 이 문서에 나온 용어\n\n', num);
    p('<!-- | 용어 | 한 줄 뜻 | [[work/knowledge/Simulink_모델읽는법]] 또는 [[work/knowledge/Stateflow_읽는법]] 링크 | -->\n\n');
    p('### %d.5 근거와 미확인\n\n', num);
    p('<!-- 확인한 것: 어떤 명령의 출력인가 / 미확인: 모델만으로는 알 수 없는 것 -->\n\n');
end
